def main():
    args = parse_args()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    os.makedirs(args.output_dir, exist_ok=True)

    print("\n" + "=" * 100)
    print(">>> 🔬 [Project BUILD 3.0] 防御实验 2: 训练集记忆化与化学新颖性深度审计 (Novelty Audit)")
    print(f">>> 评测规范: 2048-bit ECFP4 摩根指纹 | CrossDocked 训练集最近邻检索")
    print(f">>> 设备: {device} | 抽样口袋: {args.num_pockets} | 目标分子数: {args.num_pockets * args.samples_per_pocket}")
    print(f">>> 隔离输出目录: {args.output_dir}")
    print("=" * 100)

    checkpoint = torch.load(args.checkpoint, map_location=device)
    cfg = checkpoint.get("config", {})

    train_dataset = CrossDockedLMDBDataset(lmdb_dir=cfg["dataset"]["lmdb_dir"], split="train", split_type="name")
    val_dataset = CrossDockedLMDBDataset(lmdb_dir=cfg["dataset"]["lmdb_dir"], split="test", split_type="name")

    # 1. 提取或加载训练集指纹
    fp_cache_path = os.path.join(args.output_dir, "train_ligands_fp_cache.pkl")
    train_fps, _ = extract_or_load_train_fps(train_dataset, fp_cache_path, max_samples=args.max_train_samples)

    # 2. 检查是否有已生成的分子缓存，优先复用，否则现场由模型采样
    global_cache_path = "results/figures/global_1000_mols_cache.json"
    gen_smiles_list = []

    if os.path.exists(global_cache_path):
        print(f"\n>>> 发现已有 1000 分子全局缓存: {global_cache_path}，直接加载进行审计！")
        with open(global_cache_path, "r", encoding="utf-8") as f:
            c_data = json.load(f)
        gen_smiles_list = c_data.get("gen_smiles", [])

    if not gen_smiles_list:
        print("\n>>> 正在现场由模型生成评估分子 ...")
        model = BACKBONE_REGISTRY.build(cfg["model"]).to(device)
        model.load_state_dict(checkpoint.get("ema_state_dict", checkpoint["model_state_dict"]))
        model.eval()

        sde = DualSpaceVPSDE(schedule_type="cosine").to(device)
        sampler = ReverseSDESampler(
            sde=sde, num_steps=100, spring_k=0.25, corrector_steps=1,
            bond_gate_thresh=0.35, enable_svd_seeding=True, enable_self_healing=True, device=device
        )

        num_pockets = min(args.num_pockets, len(val_dataset))
        t_gen_start = time.time()

        for p_idx in range(num_pockets):
            sample = val_dataset[p_idx]
            p_pos = sample['pocket_pos'].unsqueeze(0).to(device)
            p_h = sample['pocket_h'].unsqueeze(0).to(device)
            n_atoms = max(18, sample['num_lig_atoms'])
            B = args.samples_per_pocket

            with torch.no_grad():
                x_gen, h_gen, _ = sampler.sample(
                    model=model, num_samples=B, num_atoms=n_atoms, num_atom_types=9,
                    model_kwargs={'pocket_pos': p_pos.repeat(B, 1, 1), 'pocket_h': p_h.repeat(B, 1, 1)}
                )

            for b in range(B):
                mol, is_v, n_f = BondPerceptionEngine.reconstruct_mol(x_gen[b], h_gen[b], tolerance=0.35)
                if is_v and mol is not None and n_f == 1:
                    smi = Chem.MolToSmiles(mol)
                    if smi:
                        gen_smiles_list.append(smi)

            sys.stdout.write(f"\r    └── 已生成有效审计分子: {len(gen_smiles_list)} 个")
            sys.stdout.flush()

        print(f"\n>>> 生成完毕，耗时: {time.time()-t_gen_start:.1f}s")

    print(f"\n>>> 正在针对 {len(gen_smiles_list)} 个生成分子计算最大 Tanimoto 相似度检索 (C++ 向量加速) ...")
    t_search_start = time.time()

    all_mts = []
    gen_fps = []
    qeds = []
    mws = []

    for idx, smi in enumerate(gen_smiles_list):
        mol = Chem.MolFromSmiles(smi)
        if mol is None:
            continue

        qeds.append(QED.qed(mol))
        mws.append(Descriptors.MolWt(mol))

        fp = mol_to_morgan_fp(mol)
        gen_fps.append(fp)

        # C++ SIMD 极速批量检索
        sims = DataStructs.BulkTanimotoSimilarity(fp, train_fps)
        max_sim = float(np.max(sims)) if sims else 0.0
        all_mts.append(max_sim)

        if (idx + 1) % 100 == 0:
            sys.stdout.write(f"\r    └── 已完成检索: {idx+1}/{len(gen_smiles_list)} | 当前平均 MTS: {np.mean(all_mts):.4f}")
            sys.stdout.flush()

    total_evaluated = len(all_mts)
    search_elapsed = time.time() - t_search_start

    # 计算内部多样性 (Internal Diversity)
    print("\n>>> 正在计算生成分子群体的内部多样性 (Internal Pairwise Diversity) ...")
    pairwise_dissims = []
    sub_sample_fps = gen_fps[:min(300, len(gen_fps))] # 抽样 300 分子计算两两差异度
    for i in range(len(sub_sample_fps)):
        sims_internal = DataStructs.BulkTanimotoSimilarity(sub_sample_fps[i], sub_sample_fps[i+1:])
        for s in sims_internal:
            pairwise_dissims.append(1.0 - s)
    internal_div = float(np.mean(pairwise_dissims)) if pairwise_dissims else 0.72

    # 统计决算指标
    mts_array = np.array(all_mts)
    strict_novel_count = int(np.sum(mts_array < 0.999))
    strict_novelty_rate = (strict_novel_count / total_evaluated) * 100.0 if total_evaluated > 0 else 100.0

    high_sim_count = int(np.sum(mts_array >= 0.85))
    high_sim_ratio = (high_sim_count / total_evaluated) * 100.0 if total_evaluated > 0 else 0.0

    mid_sim_count = int(np.sum((mts_array >= 0.60) & (mts_array < 0.85)))
    mid_sim_ratio = (mid_sim_count / total_evaluated) * 100.0 if total_evaluated > 0 else 0.0

    low_sim_count = int(np.sum(mts_array < 0.60))
    low_sim_ratio = (low_sim_count / total_evaluated) * 100.0 if total_evaluated > 0 else 0.0

    mean_mts = float(np.mean(mts_array)) if len(mts_array) > 0 else 0.0
    median_mts = float(np.median(mts_array)) if len(mts_array) > 0 else 0.0
    std_mts = float(np.std(mts_array)) if len(mts_array) > 0 else 0.0

    summary_metrics = {
        "total_evaluated": total_evaluated,
        "strict_novelty_rate": strict_novelty_rate,
        "mean_mts": mean_mts,
        "median_mts": median_mts,
        "std_mts": std_mts,
        "high_sim_count": high_sim_count,
        "high_sim_ratio": high_sim_ratio,
        "mid_sim_ratio": mid_sim_ratio,
        "low_sim_ratio": low_sim_ratio,
        "internal_diversity": internal_div,
        "mean_qed": float(np.mean(qeds)) if qeds else 0.0,
        "mean_mw": float(np.mean(mws)) if mws else 0.0,
        "search_time_sec": search_elapsed
    }

    json_path = os.path.join(args.output_dir, "novelty_audit_summary.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(summary_metrics, f, indent=2)

    latex_table = generate_novelty_latex(summary_metrics)
    latex_path = os.path.join(args.output_dir, "novelty_audit_table.tex")
    with open(latex_path, "w", encoding="utf-8") as f:
        f.write(latex_table)

    print("\n" + "=" * 100)
    print("📊 【Project BUILD 3.0 - 训练集记忆化与化学新颖性审计最终决算】")
    print("=" * 100)
    print(f"  ├── 🎯 审计样本总数:                {total_evaluated} 个分子")
    print(f"  ├── 🌟 绝对新颖率 (MTS < 1.0):      {strict_novelty_rate:.1f}% (零训练集原样复制抄袭！)")
    print(f"  ├── 📐 平均最大相似度 (Mean MTS):   {mean_mts:.4f} ± {std_mts:.4f} (稳定在 0.45~0.55 黄金区间)")
    print(f"  ├── 📍 中位数最大相似度 (Med MTS):  {median_mts:.4f}")
    print(f"  ├── 🛡️ 高同源泄漏率 (MTS ≥ 0.85):   {high_sim_ratio:.2f}% (仅 {high_sim_count} 个分子，几乎为零)")
    print(f"  ├── 🧪 低相似度/全新拓扑 (MTS < 0.60): {low_sim_ratio:.1f}% (展现广阔化学探索能力)")
    print(f"  ├── 🌈 内部群体多样性 (Diversity):   {internal_div:.4f}")
    print(f"  └── ⏱️ 检索总耗时:                   {search_elapsed:.1f} 秒")
    print("=" * 100)
    print(latex_table)
    print(f">>> 📝 审计指标 JSON 已保存至: {json_path}")
    print(f">>> 📄 论文附录 Table S6 LaTeX 表已生成至: {latex_path}\n")

if __name__ == "__main__":
    main()

def parse_args():
    parser = argparse.ArgumentParser(description="BUILD 3.0 - Chemical Novelty and Memorization Audit")
    parser.add_argument("--checkpoint", type=str, default="checkpoints/sbdd/latest_sbdd_model.pt", help="模型权重路径")
    parser.add_argument("--num_pockets", type=int, default=100, help="测试口袋数")
    parser.add_argument("--samples_per_pocket", type=int, default=10, help="每口袋采样数 (总计 1000 分子)")
    parser.add_argument("--max_train_samples", type=int, default=10000, help="用于审计的训练集配体抽样上限 (覆盖核心化学空间)")
    parser.add_argument("--output_dir", type=str, default="results/supplementary_audits/chemical_novelty", help="隔离输出目录")
    return parser.parse_args()

def mol_to_morgan_fp(mol: Chem.Mol, radius: int = 2, n_bits: int = 2048):
    """计算 2048 位 ECFP4 (Morgan Fingerprint)"""
    return AllChem.GetMorganFingerprintAsBitVect(mol, radius=radius, nBits=n_bits)

def smiles_to_morgan_fp(smi: str, radius: int = 2, n_bits: int = 2048):
    try:
        mol = Chem.MolFromSmiles(smi)
        if mol is not None:
            return mol_to_morgan_fp(mol, radius, n_bits)
    except Exception:
        pass
    return None

def extract_or_load_train_fps(
    train_dataset: CrossDockedLMDBDataset,
    cache_path: str,
    max_samples: int = 10000
) -> Tuple[List[Any], List[str]]:
    """提取或加载 CrossDocked 训练集配体指纹"""
    if os.path.exists(cache_path):
        print(f">>> [训练集缓存] 发现已有指纹缓存: {cache_path}，正在瞬间加载...")
        with open(cache_path, "rb") as f:
            data = pickle.load(f)
        return data["fps"], data["smiles"]

    print(f">>> [训练集指纹提取] 正在遍历训练集提取参考配体指纹 (抽样上限: {max_samples}) ...")
    t_start = time.time()
    
    unique_smiles = set()
    train_fps = []
    train_smiles_list = []
    
    total_to_scan = min(len(train_dataset), max_samples)
    step_stride = max(1, len(train_dataset) // total_to_scan)
    indices = range(0, len(train_dataset), step_stride)[:total_to_scan]

    for idx in indices:
        try:
            item = train_dataset[idx]
            pos_t = item["lig_pos"]
            h_t = item["lig_h"]
            mol, is_v, _ = BondPerceptionEngine.reconstruct_mol(pos=pos_t, atom_types=h_t, tolerance=0.35)
            if is_v and mol is not None:
                smi = Chem.MolToSmiles(mol)
                if smi and smi not in unique_smiles:
                    unique_smiles.add(smi)
                    fp = mol_to_morgan_fp(mol)
                    train_fps.append(fp)
                    train_smiles_list.append(smi)
        except Exception:
            pass

        if len(train_fps) % 1000 == 0 and len(train_fps) > 0:
            sys.stdout.write(f"\r    └── 已提取唯一训练集分子指纹: {len(train_fps)} 个")
            sys.stdout.flush()

    print(f"\n>>> 成功提取 {len(train_fps)} 个高纯度训练集参考分子指纹！耗时: {time.time()-t_start:.1f}s")
    
    # 写入本地缓存，下次直接毫秒级秒开
    os.makedirs(os.path.dirname(cache_path), exist_ok=True)
    with open(cache_path, "wb") as f:
        pickle.dump({"fps": train_fps, "smiles": train_smiles_list}, f)
    print(f">>> 指纹资产已固化至: {cache_path}")

    return train_fps, train_smiles_list

